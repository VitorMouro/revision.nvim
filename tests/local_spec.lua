local h = require('tests.helpers')
local range = require('revision.range')
local inline = require('revision.inline')
local session = require('revision.session')

local function dirty_fixture()
  local fx = h.fixture()
  h.write(fx.wt .. '/a.lua', h.read(fx.wt .. '/a.lua'):gsub('local v10 = 10', 'local v10 = 1000'))
  h.write(fx.wt .. '/untracked.lua', 'one\ntwo\n')
  vim.cmd.cd(vim.fn.fnameescape(fx.wt))
  fx.s = session.start()
  return fx
end

it('starts on working changes, untracked files included, buffers editable', function()
  local fx = dirty_fixture()
  assert(fx.s.range.worktree and fx.s.range.start == fx.c2)
  assert(fx.s.file_map['a.lua'].status == 'M')
  local u = fx.s.file_map['untracked.lua']
  assert(u and u.status == 'A' and u.additions == 2)
  for _, p in ipairs({ 'a.lua', 'untracked.lua' }) do
    vim.cmd.edit(fx.wt .. '/' .. p)
    assert(vim.bo.modifiable, p .. ' must stay editable')
    local from_buf = vim.tbl_map(function(x)
      return x.hash
    end, vim.b.revision_hunks)
    local from_git = vim.tbl_map(function(x)
      return x.hash
    end, fx.s.hunks[p])
    assert(#from_buf > 0 and vim.deep_equal(from_buf, from_git), p)
  end
end)

it('refuses every commit range while tracked files are dirty', function()
  local fx = dirty_fixture()
  local ok, err = pcall(range.apply, fx.s.merge_base, fx.s.head, 'all')
  assert(not ok and err:find('uncommitted changes'), tostring(err))
  assert(fx.s.range.worktree)
end)

it('writing a file refreshes the working file list and viewed state', function()
  local fx = dirty_fixture()
  vim.cmd.edit(fx.wt .. '/a.lua')
  require('revision.viewed').toggle_file()
  assert(require('revision.viewed').file_viewed(fx.s, 'a.lua'))
  vim.api.nvim_buf_set_lines(0, 0, 1, false, { 'edited' })
  vim.cmd('silent write')
  assert(not require('revision.viewed').file_viewed(fx.s, 'a.lua'), 'edited file must be unviewed')

  vim.cmd.edit(fx.wt .. '/brand_new.lua')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'x' })
  vim.cmd('silent write')
  assert(fx.s.file_map['brand_new.lua'], 'new file must join the list')
  assert(inline.state[vim.api.nvim_get_current_buf()], 'new file must be attached')
end)

it('clean branch with an upstream starts on unpushed commits', function()
  local fx = h.fixture()
  h.git(fx.repo, 'remote', 'add', 'origin', fx.repo)
  h.git(fx.repo, 'update-ref', 'refs/remotes/origin/feat', fx.c1)
  h.git(fx.wt, 'branch', '--set-upstream-to=origin/feat', 'feat')
  vim.cmd.cd(vim.fn.fnameescape(fx.wt))
  local s = session.start()
  assert(s.range.label == 'unpushed' and s.range.start == fx.c1 and s.range.end_ == fx.c2)
  local kinds = vim.tbl_map(function(i)
    return i.kind
  end, range.items(s))
  assert(vim.deep_equal(kinds, { 'working', 'all', 'unpushed', 'commit', 'commit' }), vim.inspect(kinds))
end)

it('a local commit made during the session moves the reviewed head', function()
  local fx = h.start()
  h.write(fx.wt .. '/new.lua', 'return 3\n')
  h.git(fx.wt, 'commit', '-qam', 'c3')
  local c3 = h.git(fx.wt, 'rev-parse', 'HEAD')
  range.items(fx.s)
  assert(fx.s.head == c3)
  range.apply(fx.s.merge_base, fx.s.head, 'all')
  assert(fx.s.hunks['new.lua'][1].new_lines[1] == 'return 3')
end)

it('reviews a repository without commits as working changes', function()
  local dir = vim.fn.tempname()
  vim.env.XDG_STATE_HOME = dir .. '/state'
  vim.fn.mkdir(dir .. '/r', 'p')
  h.git(dir .. '/r', 'init', '-q', '-b', 'main')
  h.write(dir .. '/r/a.lua', 'return 1\n')
  vim.cmd.cd(vim.fn.fnameescape(dir .. '/r'))
  local s = session.start()
  assert(s.head == nil and s.range.worktree)
  assert(s.file_map['a.lua'] and s.file_map['a.lua'].status == 'A')
  vim.cmd.edit('a.lua')
  assert(#vim.b.revision_hunks == 1 and vim.b.revision_hunks[1].hash == s.hunks['a.lua'][1].hash)
  assert(#range.items(s) == 1)
  session.stop()
end)
